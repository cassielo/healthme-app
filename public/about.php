                <h1>About</h1>
                <h2>Health Me is a healthy diet management system that helps you eat low-carbon, low-calorie food</h2>
                <br>
                <p>Global warming has been speeding up in recent years, and greenhouse gases are its most important cause,
                    so saving energy and cutting carbon emissions is urgent and cannot wait. Yet we found that while people
                    actively cut carbon in how they live and how they travel, they overlook cutting carbon in what they eat.
                    People have also been paying more and more attention to eating healthily. So we combined environmental
                    protection with health and built a system that recommends low-carbon, low-calorie food and tracks the calories and
                    carbon emissions of every meal, hoping that users can eat healthily and do their part for the planet at
                    the same time.</p>
                <br>
                <br>
                <br>
                <h1>Features</h1>
                <h2>[Personal Diet Records]</h2>
                <p>Users can record what they eat at each meal. The system calculates the calories and carbon emissions of
                    the food they eat, so they can easily keep track of their diet over time.</p>
                <br>
                <h2>[Personalized Food Recommendations]</h2>
                <p>Based on each user's quiz answers, meal records, age, sex, height and weight, the system groups
                    together people with similar eating habits. For each meal, it then recommends foods that are popular
                    in the user's group and low in carbon emissions and calories, as a reference when choosing what to eat.</p>
                <br>
                <h2>[Article Recommendations]</h2>
                <p>Based on each user's quiz answers and the articles they have read, the system recommends other articles
                    with similar content, and updates the recommendations whenever the user takes the quiz or reads an article.</p>
                <br>
                <h2>[Diet Charts]</h2>
                <p>Based on the meals each user records, the system charts the user's daily calorie intake and carbon
                    emissions next to the average of all users, so users can see how they compare and adjust their eating
                    habits.</p>
